#!/usr/bin/env bash
#
# Creates the Herdr tab topology for the health-monitoring build.
#
# Tabs, not panes: each independent workload gets its own view. The tab IDs are
# resolved from the creation responses (never predicted) and written to
# .herdr-health.env so later phases and the orchestration suite can reuse them.
#
# Topology:
#   health-api      the NestJS API server process
#   health-db       a psql session for invariant assertions
#   health-sim      the device/lab data simulator
#   health-load     the load generator
#   health-metrics  a live tail of the Prometheus scrape (tangerine_health_*)
#
# Usage:  bash scripts/herdr-health-environment.sh
#   RUN_API=0   create tabs but do not start the API in the api tab
#
set -uo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$DIR/.." && pwd)"
ENV_FILE="$ROOT/.herdr-health.env"

if [ "${HERDR_ENV:-}" != "1" ]; then
  echo "Not inside a Herdr-managed pane (HERDR_ENV != 1)." >&2
  exit 1
fi

WS="$(herdr pane current --current | python3 -c 'import sys,json;print(json.load(sys.stdin)["result"]["pane"]["workspace_id"])')"
echo "workspace: $WS"

tab_pane() { # <label> -> pane id
  herdr tab create --workspace "$WS" --label "$1" --cwd "$ROOT" --no-focus \
    | python3 -c 'import sys,json
r=json.load(sys.stdin).get("result",{})
print((r.get("root_pane") or {}).get("pane_id") or (r.get("tab") or {}).get("pane_id") or "")'
}

API_PANE="$(tab_pane health-api)"
DB_PANE="$(tab_pane health-db)"
SIM_PANE="$(tab_pane health-sim)"
LOAD_PANE="$(tab_pane health-load)"
METRICS_PANE="$(tab_pane health-metrics)"

echo "api=$API_PANE db=$DB_PANE sim=$SIM_PANE load=$LOAD_PANE metrics=$METRICS_PANE"

cat > "$ENV_FILE" <<EOF
# Generated by scripts/herdr-health-environment.sh — safe to re-run.
export HERDR_HEALTH_WORKSPACE=$WS
export HERDR_HEALTH_API_PANE=$API_PANE
export HERDR_HEALTH_DB_PANE=$DB_PANE
export HERDR_HEALTH_SIM_PANE=$SIM_PANE
export HERDR_HEALTH_LOAD_PANE=$LOAD_PANE
export HERDR_HEALTH_METRICS_PANE=$METRICS_PANE
EOF
echo "wrote $ENV_FILE"

# The db tab stays at an interactive psql prompt for assertions.
if [ -n "$DB_PANE" ]; then
  herdr pane run "$DB_PANE" \
    "docker exec -it tangerine-postgres psql -U tangerine -d tangerine" >/dev/null 2>&1 || true
fi

# The api tab boots the server (unless RUN_API=0).
if [ -n "$API_PANE" ] && [ "${RUN_API:-1}" = "1" ]; then
  herdr pane run "$API_PANE" "cd '$ROOT' && pnpm --filter @tangerine/api start:prod" >/dev/null 2>&1 || true
fi

herdr notification show "Health environment ready" \
  --body "tabs: api=$API_PANE db=$DB_PANE sim=$SIM_PANE load=$LOAD_PANE metrics=$METRICS_PANE" \
  --sound done >/dev/null 2>&1 || true
